#!/usr/bin/env node
import { readdir, mkdir, readFile, writeFile } from 'node:fs/promises';
import { realpathSync } from 'node:fs';
import { resolve, relative, dirname, extname } from 'node:path';
import { spawn } from 'node:child_process';
import { pathToFileURL } from 'node:url';

export async function generateSections(directory, output) {
  const files = (await readdir(directory, { withFileTypes: true }))
    .filter(
      (entry) =>
        entry.isFile() &&
        /\.(ts|tsx|js|jsx)$/.test(entry.name) &&
        !entry.name.startsWith('_') &&
        !entry.name.startsWith('.') &&
        !/\.(d|test|spec)\.[^.]+$/.test(entry.name) &&
        !/^index\./.test(entry.name) &&
        resolve(directory, entry.name) !== resolve(output),
    )
    .map((entry) => entry.name)
    .sort();
  const imports = files.map((file, index) => {
    let path = relative(dirname(output), resolve(directory, file))
      .split('\\')
      .join('/');
    path = path.slice(0, -extname(path).length);
    if (!path.startsWith('.')) path = `./${path}`;
    return `import section${index} from ${JSON.stringify(path)};`;
  });
  const content = `// Generated by cms-admin. Edit files in the sections folder instead.\n${imports.join('\n')}\nexport const sections = [${files.map((_, index) => `section${index}`).join(', ')}];\n`;
  await mkdir(dirname(output), { recursive: true });
  if ((await readFile(output, 'utf8').catch(() => '')) !== content)
    await writeFile(output, content);
  return files;
}

async function main(args) {
  const command = args.shift();
  if (!['generate', 'dev'].includes(command))
    throw new Error(
      'Usage: cms-admin generate|dev [--dir src/sections] [--out src/sections.generated.ts] [-- next dev]',
    );
  let directory = 'src/sections';
  let output = 'src/sections.generated.ts';
  let childArgs = [];
  while (args.length) {
    const arg = args.shift();
    if (arg === '--') {
      childArgs = args;
      break;
    }
    if (arg === '--dir' && args[0]) directory = args.shift();
    else if (arg === '--out' && args[0]) output = args.shift();
    else throw new Error(`Unknown or incomplete option: ${arg}`);
  }
  directory = resolve(directory);
  output = resolve(output);
  await generateSections(directory, output);
  if (command === 'generate') return;
  // Poll directory entries: fs.watch can miss additions on mounted or sandboxed filesystems.
  // generateSections only writes when imports change, avoiding rebuild loops.
  let generating = false;
  const watcher = setInterval(async () => {
    if (generating) return;
    generating = true;
    try {
      await generateSections(directory, output);
    } catch (error) {
      console.error(error);
    } finally {
      generating = false;
    }
  }, 300);
  if (!childArgs.length) {
    console.log(`Watching sections in ${directory}`);
    return;
  }
  const child = spawn(childArgs[0], childArgs.slice(1), {
    stdio: 'inherit',
    shell: process.platform === 'win32',
  });
  const close = () => {
    clearInterval(watcher);
  };
  child.on('error', (error) => {
    close();
    console.error(error);
    process.exitCode = 1;
  });
  child.on('exit', (code) => {
    close();
    process.exitCode = code ?? 1;
  });
  for (const signal of ['SIGINT', 'SIGTERM'])
    process.on(signal, () => {
      close();
      child.kill(signal);
    });
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href
) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
